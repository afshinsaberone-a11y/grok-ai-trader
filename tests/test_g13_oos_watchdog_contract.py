from pathlib import Path


WORKFLOW_PATH = Path(".github/workflows/forexai-g13-oos-watchdog-m15.yml")


def test_watchdog_dispatches_and_binds_exact_current_sha_safety_audit():
    workflow = WORKFLOW_PATH.read_text(encoding="utf-8")

    assert "Dispatch exact Execution Safety Audit after Promotion" in workflow
    dispatch = _workflow_step(
        workflow,
        "Dispatch exact Execution Safety Audit after Promotion",
        "Resolve exact successful Execution Safety Audit",
    )
    # The dispatch request must define its payload in this step; a payload
    # from another step is not available under bash -u and must fail tests.
    payload_assignment = 'payload="$(python -c \'import json,sys; print(json.dumps({"ref":"main","inputs":{"promotion_run_id":sys.argv[1]}}))\' "$PROMOTION_RUN_ID")"'
    assert payload_assignment in dispatch
    assert dispatch.index(payload_assignment) < dispatch.index('status="$(curl')
    assert '            --data "$payload")"' in dispatch
    assert "forexai-g13-execution-safety-audit-m15.yml/dispatches" in workflow
    assert '"promotion_run_id":sys.argv[1]' in workflow
    assert 'G13_SAFETY_AUDIT_BASELINE_ID=$safety_baseline_id' in workflow
    assert "G13_SAFETY_AUDIT_SUCCESS_RESOLVED=true" in workflow
    assert 'echo "SAFETY_AUDIT_RUN_ID=$safety_run_id" >> "$GITHUB_ENV"' in workflow
    assert 'p["head_sha"]==target' in workflow


def test_watchdog_resolves_the_single_readiness_dispatched_by_package_preflight():
    workflow = WORKFLOW_PATH.read_text(encoding="utf-8")

    # Package Preflight is the single owner of Readiness dispatch. The Watchdog
    # captures a baseline before dispatching Package Preflight, then resolves only
    # the fresh exact-SHA Readiness generated by that workflow.
    assert "Dispatch exact Readiness Gate using verified run IDs" not in workflow
    assert "forexai-g13-demo-readiness-gate-m15.yml/dispatches" not in workflow
    dispatch_start = workflow.index("      - name: Dispatch exact Controlled Demo Package Preflight")
    dispatch_end = workflow.index(
        "      - name: Resolve exact successful Controlled Demo Package Preflight",
        dispatch_start,
    )
    dispatch = workflow[dispatch_start:dispatch_end]
    baseline = dispatch.index("G13_READINESS_BASELINE_ID=$readiness_baseline_id")
    preflight_dispatch = dispatch.index(
        "forexai-g13-controlled-demo-package-preflight-m15.yml/dispatches"
    )
    assert baseline < preflight_dispatch
    assert 'r.get("event")=="workflow_dispatch"' in workflow
    assert "G13_FULL_CHAIN_READINESS_PASS" in workflow

    resolver_start = workflow.index("      - name: Resolve exact successful Demo Readiness Gate")
    resolver = workflow[resolver_start:]
    assert 'BASELINE_ID="$G13_READINESS_BASELINE_ID"' in resolver
    assert 'r.get("head_sha")==target' in resolver
    assert 'r.get("head_branch")=="main"' in resolver
    assert "G13_READINESS_SUCCESS_RESOLVED=true" in resolver

